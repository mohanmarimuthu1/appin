"""Step 2 - content audit, keyword selection and SEO content planning.

Existing content = Appin's public WordPress posts (read-only REST API, cached for a day)
+ Appin's key landing pages + every blog this agent has already generated.
A keyword is rejected or penalised when an existing page already targets it
(keyword cannibalisation).
"""
import html
import json
import os
import re
import time
from pathlib import Path

import requests

from .research import tokens

ROOT = Path(__file__).resolve().parent.parent
# Serverless hosts (Vercel, AWS Lambda) mount the code read-only; only /tmp is writable there.
WRITE_ROOT = Path("/tmp/appin") if os.environ.get("VERCEL") or os.environ.get("AWS_LAMBDA_FUNCTION_NAME") else ROOT
CACHE_FILE = WRITE_ROOT / "data" / "cache" / "appin_posts.json"
SAMPLE_FILE = ROOT / "data" / "sample_existing_posts.json"
OUTPUT_DIR = WRITE_ROOT / "output" / "blogs"
SITE = "https://appincoimbatore.com"
AGENT_HEADERS = {"User-Agent": "AppinSEOBlogAgent/1.0 (interview prototype; read-only)"}
# Function words only - question words like "how"/"after" do change the topic.
FUNCTION_WORDS = {"in", "for", "with", "the", "a", "an", "and", "of", "to", "is", "on", "at",
                  "by", "or", "me", "i", "my", "it", "are", "be", "do", "does", "can", "you", "your"}

# Real Appin pages (checked to return HTTP 200) - used for the CTA and internal links.
COURSE_PAGE = f"{SITE}/digital-marketing-course-in-coimbatore/"
KEY_PAGES = [
    {"title": "Digital Marketing Course in Coimbatore", "url": COURSE_PAGE, "type": "course page"},
    {"title": "SEO Course in Coimbatore", "url": f"{SITE}/seo-course-in-coimbatore/", "type": "course page"},
    {"title": "Online Digital Marketing Course", "url": f"{SITE}/online-digital-marketing-course-in-coimbatore/", "type": "course page"},
    {"title": "Meta Ads Mastery Course in Coimbatore", "url": f"{SITE}/meta-ads-mastery-course-coimbatore/", "type": "course page"},
    {"title": "Digital Marketing Internship in Coimbatore", "url": f"{SITE}/digital-marketing-internship-in-coimbatore/", "type": "internship page"},
    {"title": "Contact Appin Technology", "url": f"{SITE}/contact/", "type": "contact page"},
]
# Tokens too common to tell two topics apart.
GENERIC = {"digital", "marketing", "course", "courses", "coimbatore", "2024", "2025", "2026",
           "guide", "complete", "learn", "learning"}


def _norm_tokens(text):
    out = set()
    for t in tokens(text):
        if t in FUNCTION_WORDS:
            continue
        if len(t) > 3 and t.endswith("s"):
            t = t[:-1]
        out.add(t)
    return out


def load_existing_content():
    """Appin posts (live -> cache -> bundled sample) + key pages + locally generated blogs."""
    posts, source = None, "live"
    if CACHE_FILE.exists() and time.time() - CACHE_FILE.stat().st_mtime < 86400:
        posts, source = json.loads(CACHE_FILE.read_text(encoding="utf-8")), "cache (<24h)"
    if posts is None:
        try:
            posts = []
            for page in range(1, 4):
                r = requests.get(f"{SITE}/wp-json/wp/v2/posts", timeout=15, headers=AGENT_HEADERS,
                                 params={"per_page": 100, "page": page, "_fields": "title,link"})
                r.raise_for_status()
                batch = r.json()
                posts += [{"title": html.unescape(p["title"]["rendered"]),
                           "url": p["link"], "type": "appin blog post"} for p in batch]
                if len(batch) < 100:
                    break
            if not posts:
                raise ValueError("no posts returned")
            CACHE_FILE.parent.mkdir(parents=True, exist_ok=True)
            CACHE_FILE.write_text(json.dumps(posts, indent=1), encoding="utf-8")
        except Exception:
            # The site's firewall may refuse scripted requests; use the saved snapshot instead.
            posts = json.loads(SAMPLE_FILE.read_text(encoding="utf-8"))
            source = "saved snapshot of appincoimbatore.com posts (live API unavailable)"

    generated = []
    for meta in OUTPUT_DIR.glob("*/meta.json"):
        m = json.loads(meta.read_text(encoding="utf-8"))
        generated.append({"title": m["seo_title"], "url": f"/blog/{m['slug']}",
                          "type": "generated by this agent", "primary_keyword": m["primary_keyword"]})
    return {"source": source, "items": KEY_PAGES + posts + generated}


def cannibalisation(keyword, existing):
    """Score how strongly existing pages already target this keyword (0..1)."""
    kw = _norm_tokens(keyword)
    best = {"score": 0.0, "title": None, "url": None}
    for item in existing:
        t = _norm_tokens(item["title"] + " " + item.get("primary_keyword", ""))
        if not kw or not t:
            continue
        coverage = len(kw & t) / len(kw)          # how much of the keyword the page title covers
        jaccard = len(kw & t) / len(kw | t)       # how close the overall topics are
        distinct = kw - GENERIC                   # the words that make this keyword a separate topic
        if distinct and not distinct & t:
            coverage *= 0.5                       # page shares only generic words - different topic
        score = 0.65 * coverage + 0.35 * jaccard
        if item.get("primary_keyword") == keyword:
            score = 1.0
        if score > best["score"]:
            best = {"score": round(score, 2), "title": item["title"], "url": item["url"]}
    best["risk"] = "High" if best["score"] >= 0.72 else "Medium" if best["score"] >= 0.5 else "Low"
    return best


def select_cluster(keywords, existing, n_secondary=6):
    """Pick the best non-cannibalising primary keyword and a related secondary cluster."""
    candidates = []
    for k in keywords:
        if k["intent"].startswith("navigational") or k["opportunity"] <= 0:
            continue
        c = cannibalisation(k["keyword"], existing)
        penalty = {"High": 1.0, "Medium": 0.35, "Low": 0.0}[c["risk"]]
        candidates.append({**k, "cannibalisation": c,
                           "final_score": round(k["opportunity"] * (1 - penalty), 3)})
    candidates.sort(key=lambda k: k["final_score"], reverse=True)
    rejected = [k for k in candidates if k["cannibalisation"]["risk"] == "High"][:8]

    primary = candidates[0]
    p_distinct = _norm_tokens(primary["keyword"]) - GENERIC

    def related(k):
        d = _norm_tokens(k["keyword"]) - GENERIC
        return len(d & p_distinct) + (0.5 if k["intent"] == primary["intent"] else 0)

    pool = [k for k in candidates[1:60] if k["cannibalisation"]["risk"] != "High"
            and k["keyword"] != primary["keyword"]]
    pool.sort(key=lambda k: (related(k), k["final_score"]), reverse=True)
    secondary = []
    for k in pool:
        # skip near-duplicates of keywords already chosen
        if any(len(_norm_tokens(k["keyword"]) ^ _norm_tokens(s["keyword"])) <= 1
               for s in secondary + [primary]):
            continue
        secondary.append(k)
        if len(secondary) == n_secondary:
            break

    return {"primary": primary, "secondary": secondary, "rejected_cannibalising": rejected,
            "shortlist": candidates[:12]}


def internal_link_candidates(primary_keyword, existing, limit=6):
    """Key landing pages + the most topically related existing Appin posts."""
    kw = _norm_tokens(primary_keyword)
    posts = [e for e in existing if e["type"] == "appin blog post"]
    posts.sort(key=lambda e: len(kw & _norm_tokens(e["title"])), reverse=True)
    return KEY_PAGES[:5] + posts[:limit]


def unique_slug(slug):
    slug = re.sub(r"[^a-z0-9]+", "-", slug.lower()).strip("-")[:70].strip("-")
    base, n = slug, 2
    while (OUTPUT_DIR / slug).exists():
        slug, n = f"{base}-{n}", n + 1
    return slug
